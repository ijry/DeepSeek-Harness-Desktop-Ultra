/**
 * The string table: every user-visible word in the panel, in Chinese and English.
 *
 * One row per key, `[zh, en]`, so the two languages cannot drift apart — the
 * reference kept eight separate JSON files and had already let `modifiedTime`-style
 * mismatches creep in. The Chinese side is VERBATIM from otools-term's
 * `i18n/zh-CN.json` wherever the key exists there, so the port reads identically;
 * keys this port added (the AI bar, chmod, host keys, workspace transfers) are
 * marked with a comment.
 *
 * `{name}` placeholders are single-brace, like the reference.
 */

/** The active language, decided at boot (see boot.js). */
const lang = { current: 'zh' }

/** Which column of the table each language reads. */
const LANG_INDEX = { zh: 0, en: 1 }

/** Look up one key, interpolating `{name}` placeholders. */
function t(key, params) {
  const row = TEXT[key]
  if (row === undefined) return key
  const index = LANG_INDEX[lang.current] ?? 0
  const template = row[index] ?? row[0]
  if (params === undefined || params === null) return template
  return String(template).replace(/\{(\w+)\}/g, (whole, name) => (
    Object.hasOwn(params, name) ? String(params[name]) : whole
  ))
}

