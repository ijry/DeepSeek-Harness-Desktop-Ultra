门被叩了三下。

不重，像是用手背蹭上去的。这个时辰，镇上的人不会摸黑上山。沈砚提灯去开门，门一开，风把雪灌了他一脸。

台阶下跪着一个老者。皮袄冻成了硬壳，胡子上结着冰，右手裹在一团破布里，布已经黑了。他不看沈砚，只把左手往怀里按着，像按住一只想跑的东西。

“抓药。”老者说，“止血的，止痛的，能让人走到明天的。”

沈砚把他扶进来，关门落栓。解那团破布的时候他手很稳——认药比认人准，包伤也是一样的手。布下面，老者的右手少了三根指头。断口齐平，是削的，不是砍的。

“什么时候的事？”

“今日午后。”

沈砚不再问。他取三七、白芷、龙骨研末敷上，用干布缠了两圈，又抓一副撑命的汤药搁在炭炉上。老者从头到尾没哼一声，只是不肯松开怀里那样东西。

换第二道布的时候，老者忽然反手扣住他的左手腕。那只手比沈砚的还凉，扣得却很紧。

“这只手，冷得不像活人的。”老者说。

沈砚把手抽回来，塞进袖子里。铺子里只有陈九知道这件事：每年霜降以后，他左手的经脉像是结了冰，一直冻到立春才化。他不疼，只是不敢多讲。

