雪从傍晚落起，到二更时分，已经把青城山下那条石板路埋平了。九味堂的门板厚一寸，风还是从缝里钻进来，把柜台上的油灯吹得左右摇。沈砚坐在药碾子后面，左手揣在怀里没拿出来。

